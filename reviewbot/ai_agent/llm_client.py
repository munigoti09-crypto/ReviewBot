"""LLM client abstraction and implementations for ReviewBot AI Fix Agent."""

import time
from abc import ABC, abstractmethod
from typing import Optional

from reviewbot.core.config import LLMConfig
from reviewbot.utils.logger import get_logger

logger = get_logger("reviewbot.ai_agent.llm_client")


class LLMError(Exception):
    """Base exception for LLM operations."""
    pass


class LLMAuthenticationError(LLMError):
    """Raised when authentication with LLM provider fails."""
    pass


class LLMTimeoutError(LLMError):
    """Raised when LLM request times out."""
    pass


class LLMRateLimitError(LLMError):
    """Raised when LLM rate limit is encountered and retries exhausted."""
    pass


class BaseLLMClient(ABC):
    """Abstract base class for LLM providers."""

    def __init__(self, config: LLMConfig) -> None:
        self.config = config

    @abstractmethod
    def complete(self, system_prompt: str, user_prompt: str) -> str:
        """Send prompts to the LLM and return text completion.

        Args:
            system_prompt: System-level instructions.
            user_prompt: User/context prompt containing code and issues.

        Returns:
            The raw string response generated by the LLM.

        Raises:
            LLMAuthenticationError: When authentication credentials fail.
            LLMTimeoutError: When the request exceeds configured timeout.
            LLMRateLimitError: When rate limit is exceeded after retries.
            LLMError: For other unrecoverable errors.
        """
        pass


class OpenAILLMClient(BaseLLMClient):
    """OpenAI and OpenAI-compatible provider client."""

    def __init__(self, config: LLMConfig) -> None:
        super().__init__(config)
        if not self.config.api_key:
            raise LLMAuthenticationError(
                "OpenAI API key is missing. Set OPENAI_API_KEY in environment or .env file."
            )

        try:
            from openai import OpenAI
            self._client = OpenAI(
                api_key=self.config.api_key,
                base_url=self.config.base_url,
                timeout=self.config.timeout,
            )
        except Exception as e:
            raise LLMError(f"Failed to initialize OpenAI client: {e}") from e

    def complete(self, system_prompt: str, user_prompt: str) -> str:
        from openai import AuthenticationError, RateLimitError, APITimeoutError, APIError

        max_retries = max(1, self.config.max_retries)
        backoff_seconds = 1.0

        for attempt in range(1, max_retries + 1):
            try:
                logger.debug(
                    "Sending completion request to OpenAI model %s (attempt %d/%d)",
                    self.config.model,
                    attempt,
                    max_retries,
                )
                response = self._client.chat.completions.create(
                    model=self.config.model,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt},
                    ],
                    temperature=self.config.temperature,
                    response_format={"type": "json_object"},
                )
                choice = response.choices[0]
                content = choice.message.content
                if not content:
                    raise LLMError("LLM returned an empty response content.")
                return content

            except AuthenticationError as e:
                logger.error("OpenAI authentication failure: %s", e)
                raise LLMAuthenticationError("Authentication failed with OpenAI API.") from e

            except APITimeoutError as e:
                logger.warning("OpenAI timeout on attempt %d: %s", attempt, e)
                if attempt == max_retries:
                    raise LLMTimeoutError(f"OpenAI request timed out after {max_retries} attempts.") from e
                time.sleep(backoff_seconds)
                backoff_seconds *= 2.0

            except RateLimitError as e:
                logger.warning("OpenAI rate limit hit on attempt %d: %s", attempt, e)
                if attempt == max_retries:
                    raise LLMRateLimitError(
                        f"OpenAI rate limit exceeded after {max_retries} attempts."
                    ) from e
                time.sleep(backoff_seconds)
                backoff_seconds *= 2.0

            except APIError as e:
                logger.error("OpenAI API error on attempt %d: %s", attempt, e)
                if attempt == max_retries:
                    raise LLMError(f"OpenAI API error: {e}") from e
                time.sleep(backoff_seconds)
                backoff_seconds *= 2.0

            except Exception as e:
                logger.error("Unexpected error calling OpenAI: %s", e)
                raise LLMError(f"Unexpected error communicating with LLM: {e}") from e

        raise LLMError("Failed to obtain response from OpenAI.")


class GeminiLLMClient(BaseLLMClient):
    """Google Gemini provider client using official google-genai SDK."""

    def __init__(self, config: LLMConfig) -> None:
        super().__init__(config)
        if not self.config.api_key:
            raise LLMAuthenticationError(
                "Gemini API key is missing. Set GEMINI_API_KEY in environment or .env file."
            )

        try:
            from google import genai
            self._client = genai.Client(api_key=self.config.api_key)
        except Exception as e:
            raise LLMError(f"Failed to initialize Gemini client: {e}") from e

    def complete(self, system_prompt: str, user_prompt: str) -> str:
        max_retries = max(1, self.config.max_retries)
        backoff_seconds = 1.0

        for attempt in range(1, max_retries + 1):
            try:
                logger.debug(
                    "Sending completion request to Gemini model %s (attempt %d/%d)",
                    self.config.model,
                    attempt,
                    max_retries,
                )
                from google.genai import types

                combined_prompt = f"System instructions:\n{system_prompt}\n\nUser request:\n{user_prompt}"
                config_params = types.GenerateContentConfig(
                    temperature=self.config.temperature,
                    response_mime_type="application/json",
                )
                response = self._client.models.generate_content(
                    model=self.config.model,
                    contents=combined_prompt,
                    config=config_params,
                )

                text = response.text
                if not text:
                    raise LLMError("Gemini returned empty response.")
                return text

            except Exception as e:
                err_str = str(e).lower()
                if "api key" in err_str or "unauthenticated" in err_str or "permission" in err_str:
                    logger.error("Gemini authentication failure: %s", e)
                    raise LLMAuthenticationError(f"Gemini authentication failed: {e}") from e

                if "resource_exhausted" in err_str or "429" in err_str or "rate limit" in err_str:
                    logger.warning("Gemini rate limit hit on attempt %d: %s", attempt, e)
                    if attempt == max_retries:
                        raise LLMRateLimitError("Gemini rate limit exceeded.") from e
                elif "deadline" in err_str or "timeout" in err_str:
                    logger.warning("Gemini timeout on attempt %d: %s", attempt, e)
                    if attempt == max_retries:
                        raise LLMTimeoutError("Gemini request timed out.") from e
                else:
                    if attempt == max_retries:
                        raise LLMError(f"Gemini API error: {e}") from e

                time.sleep(backoff_seconds)
                backoff_seconds *= 2.0

        raise LLMError("Failed to obtain response from Gemini.")


class MockLLMClient(BaseLLMClient):
    """Configurable mock client for testing without external API calls."""

    def __init__(
        self,
        response_text: str = "",
        raises_exc: Optional[Exception] = None,
        responses: Optional[list[str]] = None,
    ) -> None:
        super().__init__(LLMConfig(api_key="mock_key"))
        self.response_text = response_text
        self.raises_exc = raises_exc
        self.responses: list[str] = list(responses or [])
        self.calls: list[tuple[str, str]] = []

    def set_response(self, response_text: str) -> None:
        """Set mock return response."""
        self.response_text = response_text
        self.raises_exc = None
        self.responses = []

    def set_exception(self, exc: Exception) -> None:
        """Set exception to be raised on complete."""
        self.raises_exc = exc

    def complete(self, system_prompt: str, user_prompt: str) -> str:
        self.calls.append((system_prompt, user_prompt))
        if self.raises_exc:
            raise self.raises_exc
        if self.responses:
            return self.responses.pop(0)
        return self.response_text


def get_llm_client(config: Optional[LLMConfig] = None) -> BaseLLMClient:
    """Factory to instantiate the appropriate LLM client based on configuration.

    Args:
        config: Optional LLMConfig instance; if omitted, loaded from environment.

    Returns:
        Configured BaseLLMClient instance.
    """
    cfg = config or LLMConfig.from_env()

    if cfg.provider == "gemini":
        return GeminiLLMClient(cfg)
    return OpenAILLMClient(cfg)
